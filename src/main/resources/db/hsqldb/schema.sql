-- Esquema del perfil hsqldb: equivalente a db/migration/V1 a V6 en
-- dialecto HSQLDB (VARCHAR(8192) en lugar de TEXT, TIMESTAMP en lugar de
-- TIMESTAMPTZ, LONGVARBINARY en lugar de BYTEA).
-- El perfil corre sin Flyway, por eso este script lo aplica
-- spring.sql.init en cada arranque.
CREATE TABLE IF NOT EXISTS asignacion (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alias_codigo VARCHAR(16) NOT NULL,
    destino      VARCHAR(8192) NOT NULL,
    creada_en    TIMESTAMP NOT NULL,
    vence_en     TIMESTAMP NOT NULL,
    CONSTRAINT uq_asignacion_alias_id UNIQUE (alias_codigo, id)
);

CREATE TABLE IF NOT EXISTS alias (
    codigo               VARCHAR(16) PRIMARY KEY,
    asignacion_actual_id BIGINT,
    -- La referencia actual siempre pertenece al mismo alias.
    CONSTRAINT fk_alias_asignacion_actual
        FOREIGN KEY (codigo, asignacion_actual_id)
        REFERENCES asignacion (alias_codigo, id)
);

-- Ciclo de claves: esta FK solo puede declararse cuando ya existen ambas
-- tablas, y ALTER no admite IF NOT EXISTS. En reinicios el ALTER falla con
-- "constraint already exists" y sql.init.continue-on-error lo omite.
ALTER TABLE asignacion
    ADD CONSTRAINT fk_asignacion_alias
    FOREIGN KEY (alias_codigo) REFERENCES alias (codigo);

-- Avance persistente de la generacion secuencial de codigos nuevos:
-- una unica fila, bloqueada con SELECT FOR UPDATE en cada reserva.
CREATE TABLE IF NOT EXISTS generador_alias (
    id             SMALLINT PRIMARY KEY CHECK (id = 1),
    proximo_indice BIGINT NOT NULL CHECK (proximo_indice >= 0)
);

INSERT INTO generador_alias (id, proximo_indice)
    SELECT 1, 0
    FROM (VALUES (1)) AS v (dummy)
    WHERE NOT EXISTS (SELECT * FROM generador_alias);

CREATE INDEX IF NOT EXISTS ix_asignacion_vence_en ON asignacion (vence_en);

-- Usuarios del login con Google (V3): se crean en el primer login.
CREATE TABLE IF NOT EXISTS usuario (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    google_sub VARCHAR(255) NOT NULL,
    email      VARCHAR(255) NOT NULL,
    namespace  VARCHAR(30),
    CONSTRAINT uq_usuario_google_sub UNIQUE (google_sub)
);

-- Namespace elegido en el primer login (V4). Se agrega con ALTER para
-- que tambien aplique a bases ya creadas; en reinicios la restriccion ya
-- existe y continue-on-error omite el ALTER (ADR 0005).
ALTER TABLE usuario
    ADD CONSTRAINT uq_usuario_namespace UNIQUE (namespace);

-- Asignaciones de enlaces personales (V5): pertenecen al usuario, no al
-- texto del namespace; el historial se conserva (ADR 0003).
CREATE TABLE IF NOT EXISTS asignacion_personal (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id          BIGINT       NOT NULL,
    alias_personalizado VARCHAR(50)  NOT NULL,
    destino             VARCHAR(8192) NOT NULL,
    creada_en           TIMESTAMP    NOT NULL,
    vence_en            TIMESTAMP    NOT NULL,
    CONSTRAINT fk_asignacion_personal_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuario (id)
);

CREATE INDEX IF NOT EXISTS ix_asignacion_personal_usuario_alias
    ON asignacion_personal (usuario_id, alias_personalizado);

CREATE TABLE IF NOT EXISTS nombre_namespace (
    namespace     VARCHAR(30) PRIMARY KEY,
    usuario_id    BIGINT NOT NULL,
    grace_ends_at TIMESTAMP,
    CONSTRAINT fk_nombre_namespace_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id)
);
CREATE INDEX IF NOT EXISTS ix_nombre_namespace_grace_ends_at
    ON nombre_namespace (grace_ends_at);
INSERT INTO nombre_namespace (namespace, usuario_id)
    SELECT u.namespace, u.id FROM usuario u
    WHERE u.namespace IS NOT NULL
      AND NOT EXISTS (SELECT 1 FROM nombre_namespace n WHERE n.namespace = u.namespace);
CREATE TABLE IF NOT EXISTS namespace_anterior (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id    BIGINT       NOT NULL,
    namespace     VARCHAR(30)  NOT NULL,
    grace_ends_at TIMESTAMP    NOT NULL,
    CONSTRAINT fk_namespace_anterior_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT fk_namespace_anterior_nombre FOREIGN KEY (namespace) REFERENCES nombre_namespace (namespace),
    CONSTRAINT uq_namespace_anterior_namespace UNIQUE (namespace)
);
CREATE INDEX IF NOT EXISTS ix_namespace_anterior_grace_ends_at
    ON namespace_anterior (grace_ends_at);

-- Spring Session JDBC (V3): LONGVARBINARY en lugar de BYTEA.
CREATE TABLE IF NOT EXISTS spring_session (
    primary_id            CHAR(36)     NOT NULL,
    session_id            CHAR(36)     NOT NULL,
    creation_time         BIGINT       NOT NULL,
    last_access_time      BIGINT       NOT NULL,
    max_inactive_interval INT          NOT NULL,
    expiry_time           BIGINT       NOT NULL,
    principal_name        VARCHAR(100),
    CONSTRAINT spring_session_pk PRIMARY KEY (primary_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS spring_session_ix1 ON spring_session (session_id);
CREATE INDEX IF NOT EXISTS spring_session_ix2 ON spring_session (expiry_time);
CREATE INDEX IF NOT EXISTS spring_session_ix3 ON spring_session (principal_name);

CREATE TABLE IF NOT EXISTS spring_session_attributes (
    session_primary_id CHAR(36)      NOT NULL,
    attribute_name     VARCHAR(200)  NOT NULL,
    attribute_bytes    LONGVARBINARY NOT NULL,
    CONSTRAINT spring_session_attributes_pk
        PRIMARY KEY (session_primary_id, attribute_name),
    CONSTRAINT spring_session_attributes_fk
        FOREIGN KEY (session_primary_id)
        REFERENCES spring_session (primary_id) ON DELETE CASCADE
);
