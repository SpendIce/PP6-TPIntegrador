-- Issue #24: reserva exclusiva de namespaces actuales y anteriores.
-- Namespaces actuales y anteriores comparten este registro único para que
-- una reserva vigente sea exclusiva incluso ante cambios concurrentes.
CREATE TABLE nombre_namespace (
    namespace VARCHAR(30) PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuario (id),
    grace_ends_at TIMESTAMPTZ
);
INSERT INTO nombre_namespace (namespace, usuario_id)
    SELECT namespace, id FROM usuario WHERE namespace IS NOT NULL;
CREATE INDEX ix_nombre_namespace_grace_ends_at
    ON nombre_namespace (grace_ends_at);

-- Namespace anteriores con fin de gracia inmutable (issue #24).
CREATE TABLE namespace_anterior (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id    BIGINT       NOT NULL REFERENCES usuario (id),
    namespace     VARCHAR(30)  NOT NULL REFERENCES nombre_namespace (namespace),
    grace_ends_at TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_namespace_anterior_namespace UNIQUE (namespace)
);
CREATE INDEX ix_namespace_anterior_grace_ends_at
    ON namespace_anterior (grace_ends_at);
