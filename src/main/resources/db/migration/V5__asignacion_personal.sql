-- Etapa 2 (issue #21): asignaciones de enlaces personales. Pertenecen al
-- usuario (no al texto del namespace) y guardan el alias personalizado,
-- el destino, la creacion y el vencimiento. El historial se conserva
-- como el de asignacion (ADR 0003): al vencer, el mismo usuario puede
-- volver a usar el alias. La traduccion HSQLDB vive en
-- db/hsqldb/schema.sql (ADR 0005).

CREATE TABLE asignacion_personal (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id          BIGINT      NOT NULL,
    alias_personalizado VARCHAR(50) NOT NULL,
    destino             TEXT        NOT NULL,
    creada_en           TIMESTAMPTZ NOT NULL,
    vence_en            TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_asignacion_personal_usuario
        FOREIGN KEY (usuario_id) REFERENCES usuario (id)
);

-- Resolucion de /{namespace}/{alias}: el namespace ubica al usuario y
-- este indice su asignacion vigente de ese alias personalizado.
CREATE INDEX ix_asignacion_personal_usuario_alias
    ON asignacion_personal (usuario_id, alias_personalizado);
