-- Etapa 2 (issue #19): usuarios identificados por el sub de Google y
-- sesiones persistidas con Spring Session JDBC (ADR 0007). La traduccion
-- HSQLDB vive en db/hsqldb/schema.sql (ADR 0005).

-- Persona identificada por su cuenta de Google; se crea en el primer
-- login y se reutiliza en los siguientes. namespace queda vacio hasta
-- que el usuario lo elija (Change posterior).
CREATE TABLE usuario (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    google_sub VARCHAR(255) NOT NULL,
    email      VARCHAR(255) NOT NULL,
    namespace  VARCHAR(30),
    CONSTRAINT uq_usuario_google_sub UNIQUE (google_sub)
);

-- Spring Session JDBC (org.springframework.session.jdbc): cada sesion
-- guarda su inactividad maxima y sus atributos (usuario_id, sesion_tipo).
CREATE TABLE spring_session (
    primary_id            CHAR(36)     NOT NULL,
    session_id            CHAR(36)     NOT NULL,
    creation_time         BIGINT       NOT NULL,
    last_access_time      BIGINT       NOT NULL,
    max_inactive_interval INT          NOT NULL,
    expiry_time           BIGINT       NOT NULL,
    principal_name        VARCHAR(100),
    CONSTRAINT spring_session_pk PRIMARY KEY (primary_id)
);

CREATE UNIQUE INDEX spring_session_ix1 ON spring_session (session_id);
CREATE INDEX spring_session_ix2 ON spring_session (expiry_time);
CREATE INDEX spring_session_ix3 ON spring_session (principal_name);

CREATE TABLE spring_session_attributes (
    session_primary_id CHAR(36)      NOT NULL,
    attribute_name     VARCHAR(200)  NOT NULL,
    attribute_bytes    BYTEA         NOT NULL,
    CONSTRAINT spring_session_attributes_pk
        PRIMARY KEY (session_primary_id, attribute_name),
    CONSTRAINT spring_session_attributes_fk
        FOREIGN KEY (session_primary_id)
        REFERENCES spring_session (primary_id) ON DELETE CASCADE
);
